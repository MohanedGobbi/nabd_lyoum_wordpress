wp_() { wp --allow-root "$@"; }

new_post() {
  local title="$1" cat="$2" content="$3" days_ago="$4" tag="$5"
  local id
  id=$(wp_ post create --post_type=post --post_status=publish \
    --post_title="$title" --post_content="$content" \
    --post_category="$cat" \
    --post_date="$(date -d "-$days_ago hours" '+%Y-%m-%d %H:%M:%S')" \
    --porcelain)
  if [ -n "$tag" ]; then
    wp_ post term add "$id" post_tag "$tag" >/dev/null
  fi
  echo "$id"
}

